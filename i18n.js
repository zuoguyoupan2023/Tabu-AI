  let currentLang = 'zh';
  const listeners = [];

  // 系统语言：zh 开头 → 中文；否则英文（en 为回退）
  function systemLang() {
    const nl = (navigator.language || '').toLowerCase();
    return nl.startsWith('zh') ? 'zh' : 'en';
  }

  // 取词：{0}/{1} 依次替换 args
  function t(key, ...args) {
    let s = (DICT[currentLang] && DICT[currentLang][key]) || (DICT.en && DICT.en[key]) || key;
    if (args && args.length) {
      // 用函数替换，避免参数里的 $ 被当作特殊替换模式（如 $& / $1）
      args.forEach((a, i) => { s = s.replace(new RegExp('\\{' + i + '\\}', 'g'), () => String(a)); });
    }
    return s;
  }

  // 读取指定语言的原文（用于跨语言判断，如卡片示例文本是否仍为默认）
  function raw(key, lang) {
    const d = lang === 'zh' ? DICT.zh : DICT.en;
    return (d && d[key]) || key;
  }

  function apply() {
    document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';
    document.title = t('appTitle');
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    // 富文本文案（如欢迎/卸载页里含 <strong> 的段落）：用 innerHTML 渲染，文案源自带可信任 HTML
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });
    document.querySelectorAll('[data-i18n-alt]').forEach((el) => {
      el.alt = t(el.dataset.i18nAlt);
    });
    // 语言切换按钮：显示目标语言（中文模式显示 EN，英文模式显示 汉）
    const btn = document.getElementById('btnLang');
    if (btn) {
      btn.textContent = currentLang === 'zh' ? 'EN' : '汉';
      btn.title = t(currentLang === 'zh' ? 'switchToEn' : 'switchToZh');
    }
    // 通知动态列表重渲染
    listeners.forEach((fn) => { try { fn(); } catch (e) {} });
  }

  // 语言偏好读写：扩展页用 chrome.storage.local；独立托管页（卸载页等）无 chrome.storage 时回退 localStorage，
  // 保证同一套 I18N 在两种环境都能用（欢迎页为扩展页、卸载页为托管网页）。
  function hasChromeStorage() {
    return typeof chrome !== 'undefined' && chrome.storage && chrome.storage.local;
  }
  async function readStoredLang() {
    if (hasChromeStorage()) {
      try {
        const r = await chrome.storage.local.get(STORAGE_KEY);
        return r[STORAGE_KEY];
      } catch (e) { return null; }
    }
    try { return localStorage.getItem(STORAGE_KEY); } catch (e) { return null; }
  }
  async function writeStoredLang(lang) {
    if (hasChromeStorage()) {
      try { await chrome.storage.local.set({ [STORAGE_KEY]: lang }); } catch (e) {}
      return;
    }
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  async function init() {
    currentLang = (await readStoredLang()) || systemLang();
    apply();
  }

  async function toggle() {
    currentLang = currentLang === 'zh' ? 'en' : 'zh';
    await writeStoredLang(currentLang);
    apply();
  }

  function onApply(fn) {
    if (typeof fn === 'function') listeners.push(fn);
  }

  return { init, toggle, apply, t, raw, onApply };
